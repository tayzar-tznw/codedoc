// Package trace is the runtime oracle: every probe target calls Hit, which
// records (call-site file:line, caller function) -> callee function.
package trace

import (
	"encoding/json"
	"os"
	"runtime"
	"strings"
	"sync"
)

type Rec struct {
	CallerFile string `json:"caller_file"`
	CallerLine int    `json:"caller_line"`
	CallerFunc string `json:"caller_func"`
	Callee     string `json:"callee"`
	CalleeFile string `json:"callee_file"`
	CalleeLine int    `json:"callee_line"`
	Note       string `json:"note,omitempty"`
}

var (
	mu   sync.Mutex
	seen = map[Rec]bool{}
	recs []Rec
)

func wrapper(f runtime.Frame) bool {
	return f.File == "<autogenerated>" || strings.HasSuffix(f.Function, "-fm")
}

func record(r Rec) {
	mu.Lock()
	defer mu.Unlock()
	if !seen[r] {
		seen[r] = true
		recs = append(recs, r)
	}
}

// Hit records the immediate caller of the function that calls Hit,
// skipping compiler-generated wrapper frames.
func Hit() { hit("") }

// HitNote is Hit with a free-form note (e.g. a dynamic type).
func HitNote(note string) { hit(note) }

func hit(note string) {
	pc := make([]uintptr, 16)
	n := runtime.Callers(3, pc) // skip Callers, hit, Hit
	frames := runtime.CallersFrames(pc[:n])
	callee, more := frames.Next()
	if !more {
		return
	}
	fn := runtime.FuncForPC(callee.Entry)
	cfile, cline := "", 0
	if fn != nil {
		cfile, cline = fn.FileLine(callee.Entry)
	}
	for {
		caller, more := frames.Next()
		if wrapper(caller) && more {
			continue
		}
		record(Rec{caller.File, caller.Line, caller.Function, callee.Function, cfile, cline, note})
		return
	}
}

// Dump writes all records as JSON lines to $TRACE_OUT (appending).
func Dump() {
	out := os.Getenv("TRACE_OUT")
	if out == "" {
		return
	}
	f, err := os.OpenFile(out, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o644)
	if err != nil {
		panic(err)
	}
	defer f.Close()
	mu.Lock()
	defer mu.Unlock()
	enc := json.NewEncoder(f)
	for _, r := range recs {
		enc.Encode(r)
	}
}

// Dyn records the dynamic type observed at a probe site (for targets that
// cannot call Hit, such as stdlib methods).
func Dyn(id, dynType string) {
	_, file, line, _ := runtime.Caller(1)
	record(Rec{CallerFile: file, CallerLine: line, Callee: "dyn:" + dynType, Note: id})
}
